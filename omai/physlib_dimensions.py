"""Current, additive seven-base ISQ dimension encoding for the Physlib bridge.

This module deliberately does not change ``physlean_export`` or the historical
Lean 4.31 package. Every catalog field is accounted for, including promoted
parameters and multi-field nodes. Opaque dimensions are gaps, never unitless.
The generated witnesses check dimensions only, not units or physical models.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from omai.map_data import DOMAINS, build_graph_dict
from omai.operator import dimensions

PHYSLIB_REV = "9b583cb6ef6e9cc537c4d4b786b508de1abbcf42"
LEAN_TOOLCHAIN = "leanprover/lean4:v4.35.0"
ISQ_BASES = ("mass", "length", "time", "temperature", "amount", "current", "luminousIntensity")
_ROOT = Path(__file__).resolve().parents[1]


def _ident(text: str) -> str:
    value = re.sub(r"[^a-zA-Z0-9_]", "_", text)
    return re.sub(r"_+", "_", value).strip("_")


def dimension_records() -> list[dict]:
    """Return complete, stable field records keyed by immutable catalog uid."""
    graph = build_graph_dict(DOMAINS)
    nodes = {n.name: n for d in DOMAINS for n in d.nodes}
    known_dimensions = {v.name: v for v in vars(dimensions).values()
                        if isinstance(v, dimensions.Dimension)}
    promoted = {p[0]: p[3] for d in DOMAINS for p in d.param_promotions if len(p) >= 4}
    records = []
    for n in sorted(graph["nodes"], key=lambda item: item["id"]):
        node = nodes.get(n["id"])
        fields = [(f.name, f.dimension, list(f.indices)) for f in node.fields] if node else [
            ("parameter", known_dimensions[promoted[n["id"]]], [])]
        for field, dim, indices in fields:
            ident = "dimension_" + _ident(n["id"]) + "_field_" + _ident(field)
            records.append({"node": n["id"], "node_uid": n["uid"], "field": field,
                            "dimension": dim.name, "indices": indices,
                            "exponents": list(dim.exponents) if dim.exponents is not None else None,
                            "declaration": ("OMAI.PhyslibBridge.ISQ." + ident
                                            if dim.exponents is not None else None),
                            "status": "encoded" if dim.exponents is not None else "opaque"})
    declarations = [r["declaration"] for r in records if r["declaration"]]
    if len(declarations) != len(set(declarations)):
        raise ValueError("ISQ declaration name collision")
    return records


def build_dimensions_export() -> tuple[str, dict]:
    records = dimension_records()
    lines = [
        "/- Generated by python -m omai.physlib_dimensions.",
        "   Native Physlib seven-base ISQ encodings; dimensional evidence only.",
        "   OMAI tuple order: M, L, T, Th, N, I, J (explicitly matched below).",
        "   No unit-scale, frequency convention, formula or numeric-code proof is implied.",
        f"   Physlib revision: {PHYSLIB_REV}.",
        "-/",
        "module",
        "public import Physlib.Units.ISQDimensionBase",
        "@[expose] public section",
        "",
        "namespace OMAI.PhyslibBridge.ISQ",
        "",
        "open Dimension",
        "",
    ]
    for r in records:
        if r["status"] == "opaque":
            lines.append(f"-- Opaque dimension omitted: {r['node']} / {r['field']}.")
            continue
        ident = r["declaration"].rsplit(".", 1)[1]
        lines.extend([f"-- {r['node']} / {r['field']}; uid {r['node_uid']}",
                      f"def {ident} : Dimension ISQDimensionBase := ofFunction fun"])
        lines.extend(f"  | .{base} => {power}" for base, power in zip(ISQ_BASES, r["exponents"]))
        # All seven projections are checked against the original OMAI tuple;
        # this is an encoding witness, not an operator/model theorem.
        propositions = [f"{ident}.exponent .{base} = {power}"
                        for base, power in zip(ISQ_BASES, r["exponents"])]
        lines.append(f"theorem {ident}_exponents :")
        lines.append("    " + " ∧\n    ".join(propositions) + " := by decide")
        lines.append("")
    lines.extend(["end OMAI.PhyslibBridge.ISQ", ""])
    stats = {"physlib_rev": PHYSLIB_REV, "lean_toolchain": LEAN_TOOLCHAIN,
             "catalog_nodes": len({r["node"] for r in records}), "fields": len(records),
             "encoded_fields": sum(r["status"] == "encoded" for r in records),
             "opaque_fields": sum(r["status"] == "opaque" for r in records),
             "records": records}
    return "\n".join(lines), stats


def main() -> None:
    source, stats = build_dimensions_export()
    path = _ROOT / "lean" / "bridge" / "OMAIPhyslibDimensions.lean"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source)
    (_ROOT / "docs/data/physlib_dimensions.json").write_text(
        json.dumps(stats, indent=2, ensure_ascii=False) + "\n")
    print(json.dumps({key: value for key, value in stats.items() if key != "records"}, sort_keys=True))


if __name__ == "__main__":
    main()
