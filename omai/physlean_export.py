"""The browser index of the Lean layer (docs/data/lean.json).

There is one Lean package, ``lean/bridge``, pinned to one Physlib revision and
one toolchain (``omai.physlib_dimensions.PHYSLIB_REV`` and ``LEAN_TOOLCHAIN``).
Each map node's dimension is a Physlib seven-base ``Dimension
ISQDimensionBase`` declaration in ``lean/bridge/OMAIPhyslibDimensions.lean``,
generated by ``omai.physlib_dimensions``. This module publishes the same
declarations, keyed by node id, so the map and the playground can show them.
Nodes whose dimension is opaque (a potential, a structure) have no entry.

Formula theorems are not listed here: the compiled formula bridges, their
conditions and their evidence are in ``docs/data/formula_bindings.json``.

CLI:  python -m omai.physlean_export   ->  writes docs/data/lean.json
"""
from __future__ import annotations

import json
from pathlib import Path

from omai.physlib_dimensions import (
    LEAN_TOOLCHAIN, PHYSLIB_REV, declaration_source, dimension_records,
)

_REPO = Path(__file__).resolve().parent.parent


def json_version():
    p = _REPO / "docs" / "data" / "version.json"
    if p.exists():
        try:
            return json.loads(p.read_text()).get("version")
        except Exception:
            return None
    return None


def build_lean_index() -> dict:
    """node id -> the Lean declaration of each encoded field, in field order."""
    nodes: dict[str, dict] = {}
    for r in dimension_records():
        if r["status"] != "encoded":
            continue
        entry = nodes.setdefault(r["node"], {"lean": "", "fields": []})
        entry["fields"].append({"field": r["field"], "declaration": r["declaration"],
                                "exponents": r["exponents"]})
        entry["lean"] = "\n".join(filter(None, (entry["lean"], declaration_source(r))))
    return {
        "version": (json_version() or "")[:12],
        "physlib_rev": PHYSLIB_REV,
        "lean_toolchain": LEAN_TOOLCHAIN,
        "source": "lean/bridge/OMAIPhyslibDimensions.lean",
        "nodes": nodes,
    }


def write_export(out: Path | None = None):
    out = out or (_REPO / "docs" / "data" / "lean.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    index = build_lean_index()
    out.write_text(json.dumps(index, separators=(",", ":"), sort_keys=True))
    return out, {"nodes": len(index["nodes"]),
                 "fields": sum(len(n["fields"]) for n in index["nodes"].values())}


if __name__ == "__main__":  # pragma: no cover - CLI
    path, stats = write_export()
    print(f"wrote {path}")
    for k, v in stats.items():
        print(f"  {k}: {v}")
