"""The code landing pages (docs/codes/<key>/), one per public code on the map.

Each page is generated by omai.code_pages from the published data: it opens with the
infographic drawn from the code's brief, states what the code is and computes (with its
submap drawn inline), lists the curated references and the citation line. The build is deterministic and complete,
the references carry resolvable DOIs, and the pages are discoverable (sitemap, llms.txt,
the bibliography links to them).
"""

import json
import re
import subprocess
import sys
from pathlib import Path

from omai import briefs, code_pages, glyphs, submap

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
CODES = json.loads((DOCS / "data" / "codes.json").read_text())
REGISTRY = json.loads((DOCS / "data" / "registry.json").read_text())["code"]
PUBLIC = sorted(k for k in CODES if (REGISTRY.get(k) or {}).get("visibility") != "private")
DOI = re.compile(r"^10\.\d{4,9}/\S+$")


def test_every_public_code_has_a_page_and_private_ones_do_not():
    on_disk = sorted(p.parent.name for p in (DOCS / "codes").glob("*/index.html"))
    assert on_disk == PUBLIC
    posters = sorted(p.parent.parent.name for p in (DOCS / "codes").glob("*/infographic/index.html"))
    assert posters == PUBLIC


def test_generation_is_deterministic(tmp_path, monkeypatch):
    monkeypatch.setattr(code_pages, "OUT", tmp_path / "codes")
    monkeypatch.setattr(code_pages, "CARDS", tmp_path / "og")
    code_pages.build(write_cards=False)
    before = {p: p.read_bytes() for p in (tmp_path / "codes").rglob("index.html")}
    code_pages.build(write_cards=False)
    after = {p: p.read_bytes() for p in (tmp_path / "codes").rglob("index.html")}
    assert before == after and len(before) == 2 * len(PUBLIC)  # the page and its poster page


def test_committed_pages_match_the_generator(tmp_path, monkeypatch):
    monkeypatch.setattr(code_pages, "OUT", tmp_path / "codes")
    monkeypatch.setattr(code_pages, "CARDS", DOCS / "assets" / "og" / "codes")  # cards exist, so og:image points at them
    code_pages.build(write_cards=False)
    for key in PUBLIC:
        for rel in ("index.html", "infographic/index.html", "infographic/card.html"):
            assert (tmp_path / "codes" / key / rel).read_text() == (DOCS / "codes" / key / rel).read_text(), \
                f"{key}/{rel}: run PYTHONPATH=. python -m omai.code_pages and commit"


def test_the_infographic_comes_first_and_the_record_follows():
    for key in PUBLIC:
        html = (DOCS / "codes" / key / "index.html").read_text()
        article = html.split('<article class="prose gwrap">', 1)[1]
        assert article.lstrip().startswith('<figure class="gsec info-figure" id="infographic">'), key
        assert '<svg class="submap-svg"' in article, key + ": the submap is drawn inline"
        assert f'href="../../map/#code={key}"' in article, key
        assert f"&lt;iframe src=&quot;https://openmaterials.ai/map/?embed=1#code={key}&quot;" in html, "the embed snippet is on the page"
        for anchor in ("about", "detail", "serves", "references", "cite"):
            assert f'id="{anchor}"' in article, (key, anchor)
        assert f'<link rel="canonical" href="https://openmaterials.ai/codes/{key}/">' in html
        assert chr(0x2014) not in html, key + ": em dash"
        poster = (DOCS / "codes" / key / "infographic" / "index.html").read_text()
        assert '<meta name="robots" content="noindex">' in poster and 'class="info poster' in poster, key


def test_every_public_code_has_a_valid_brief():
    for key in PUBLIC:
        brief = briefs.load(key)
        assert brief, key + ": no brief under docs/data/briefs/"
        refs_path = DOCS / "data" / "references" / f"{key}.json"
        refs = json.loads(refs_path.read_text()) if refs_path.exists() else None
        assert briefs.validate(brief, refs) == [], key
        assert brief["key"] == key
    assert not (set(p.stem for p in briefs.BRIEFS.glob("*.json")) - set(PUBLIC)), "a brief for a code that has no page"


def test_every_glyph_the_briefs_may_name_is_drawn():
    assert set(briefs.GLYPHS) == set(glyphs.GLYPHS)
    for name in briefs.GLYPHS:
        assert glyphs.svg(name).startswith("<svg ") and "<" in glyphs.GLYPHS[name]


def test_submap_names_and_symbols():
    graph = json.loads((DOCS / "data" / "graph.json").read_text())
    for node in graph["nodes"]:
        assert submap.symbol_runs(node["symbol"]) is not None, node["symbol"]
    assert submap.node_name("ThermalConductivity[transport_model=green_kubo]") == "Thermal conductivity (Green-Kubo)"
    assert submap.node_name("PhaseSpace3Phonon") == "Three-phonon phase space"
    assert submap.symbol_html("\\kappa_{\\mathrm{gk}}") == "κ<sub>gk</sub>"
    for key in PUBLIC:
        out = submap.svg(graph, set(CODES[key]))
        for node in CODES[key]:
            assert f'href="../../map/#node={code_pages.esc(node)}"' in out, (key, node)


def test_every_served_quantity_is_listed_and_linked():
    for key in PUBLIC:
        html = (DOCS / "codes" / key / "index.html").read_text()
        for node in CODES[key]:
            assert f'href="../../map/#node={code_pages.esc(node)}"' in html, (key, node)


def test_references_have_doi_shape_and_are_grouped():
    seen = 0
    for path in sorted((DOCS / "data" / "references").glob("*.json")):
        refs = json.loads(path.read_text())
        assert refs["key"] == path.stem and refs["key"] in CODES
        for group in ("code", "methods", "applications"):
            for r in refs[group]:
                assert DOI.match(r["doi"]), (path.stem, r["doi"])
                assert r["title"] and r["authors"] and r["year"], (path.stem, r["title"])
                seen += 1
        assert refs["code"], path.stem + ": a list without the code's own paper"
    assert seen > 100


def test_pages_are_discoverable():
    sitemap = (DOCS / "sitemap.xml").read_text()
    llms = (DOCS / "llms.txt").read_text()
    bibliography = (DOCS / "codes" / "index.html").read_text()
    for key in PUBLIC:
        assert f"<loc>https://openmaterials.ai/codes/{key}/</loc>" in sitemap, key
    assert "/codes/<key>/" in llms or "/codes/gpumd/" in llms
    assert "Code page" in bibliography and "privateCodes[name] ? ''" in bibliography, \
        "the card links its code page, except for a private code"


def test_map_embed_markup_present_and_script_parses(tmp_path):
    # the embed mode of the full map stays for the snippet under each submap
    page = (DOCS / "map" / "index.html").read_text()
    assert "get('embed')==='1'" in page
    assert "body.embed .toolbar" in page and "body.embed [data-site-header]" in page
    assert 'id="embedBtn"' in page and 'id="embedOut"' in page and 'target="_top"' in page
    script = max(re.findall(r"<script>(.*?)</script>", page, re.S), key=len)
    probe = tmp_path / "map_probe.js"
    probe.write_text("(async function(){" + script + "})();")
    subprocess.run(["node", "--check", str(probe)], check=True)


def test_hand_written_text_stays_within_the_roster():
    text = json.loads((DOCS / "data" / "code_pages.json").read_text())
    for key, entry in text.items():
        if key.startswith("_"):
            continue
        assert key in CODES, key
        assert entry.get("tagline") and entry.get("summary"), key
        assert chr(0x2014) not in json.dumps(entry), key
